'''We are currently in Advanced Python 2, and you are learning about Virtual Environments (venv).

Let's continue from here.

📌 What is a Virtual Environment?

A virtual environment is an isolated Python environment for a specific project.

For example:

Project A needs Django version X
Project B needs a different version
A virtual environment keeps their packages separate.

Typical commands are:

python -m venv myenv

Activate it on Windows PowerShell:
.\AdvancePython2\env\Scripts\Activate.ps1

Or in Command Prompt:

myenv\Scripts\activate 

After activation, you'll usually see something like:

(myenv) C:\YourProject>'''